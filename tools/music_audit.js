// Overnight Oct 17, Part 12: the music audit.
//   node tools/music_audit.js
// Rates every track in data/audio/audio_registry.json 1-5 from what can be measured and what the music list says it is for:
// loudness after the game's gain (does it reach the -20 LUFS loop / -17 LUFS sting target under the -1.5 dB peak ceiling?),
// dynamic range (LRA), the loop seam (data/source/audio_levels.csv on the delivered file, and docs/audio/loop_fixes.md for what
// tools/loop_fix.js changed), repetitiveness (how short the loop is) and mood fit (the track's own name, category and use
// against the place it plays). Nobody listened: the scores rank what to look at first. Writes docs/audio/music_audit.md.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'data/audio/audio_registry.json'), 'utf8')).entries;
const levels = {};
for (const line of fs.readFileSync(path.join(root, 'data/source/audio_levels.csv'), 'utf8').trim().split('\n').slice(1)) {
	const c = line.split(',');
	levels[c[0]] = { loop: c[2] === '1', lufs: parseFloat(c[5]), peak: parseFloat(c[6]), lra: parseFloat(c[7]), click: parseFloat(c[8]), gap: parseFloat(c[9]), jump: parseFloat(c[10]), flags: (c[13] || '').trim() };
}
const fixes = {};
const fixDoc = path.join(root, 'docs/audio/loop_fixes.md');
if (fs.existsSync(fixDoc)) for (const line of fs.readFileSync(fixDoc, 'utf8').split('\n')) {
	const m = line.match(/^\| (MUS-[\w-]+) \|[^|]+\|[^|]+\|[^|]+\| ([\d.]+) \/ (-?[\d.]+) \/ ([\d.]+) \|/);
	if (m) fixes[m[1]] = { gap: parseFloat(m[2]), jump: parseFloat(m[3]) };
}
const TARGET = { loop: -20, sting: -17 };
const rows = [];
for (const [id, e] of Object.entries(registry)) {
	if (e.alias_of) continue;
	const lv = levels[id];
	const notes = [];
	let score = 5;
	const isSting = id.startsWith('STG-') || e.kind === 'sting';
	if (!e.gameplay) notes.push('composition reference (never plays)');
	if (lv) {
		const heard = lv.lufs + (e.volume_db || 0);
		const off = heard - (isSting ? TARGET.sting : TARGET.loop);
		if (Math.abs(off) > 3) { score -= 1; notes.push(`mix: plays ${off > 0 ? 'loud' : 'quiet'} (${heard.toFixed(1)} LUFS after gain; the peaks stop it reaching the target)`); }
		if (lv.lra > 15) { score -= 1; notes.push(`mix: very wide dynamics (LRA ${lv.lra} LU): quiet passages vanish under battle sounds`); }
		else if (lv.lra < 2.5 && !isSting) notes.push(`mix: flat dynamics (LRA ${lv.lra} LU)`);
		if (lv.loop) {
			const fix = fixes[id];
			if (fix) {
				if (Math.abs(fix.jump) > 6) { score -= 1; notes.push(`loop: seam fixed but still steps ${fix.jump.toFixed(1)} dB at the wrap`); }
				else notes.push(`loop: seam fixed (was ${lv.flags || 'a click'})`);
			} else if (lv.flags) { score -= 1; notes.push(`loop: ${lv.flags}`); }
			else notes.push('loop: clean seam');
			const seconds = e.duration || 0;
			if (seconds > 0 && seconds < 75) { score -= 1; notes.push(`repetitive: a ${seconds.toFixed(0)} s loop repeats often`); }
			else if (seconds >= 150) notes.push(`long loop (${seconds.toFixed(0)} s)`);
		}
	} else notes.push('no analysis (not in audio_levels.csv)');
	const text = `${e.name} ${e.use} ${e.category} ${e.zone}`.toLowerCase();
	if (/placeholder|temp|stand-?in/.test(text)) { score -= 1; notes.push('mood: marked as a placeholder'); }
	rows.push({ id, name: e.name, zone: e.zone || '', category: e.category || '', use: e.use || '', score: Math.max(1, score), notes, gameplay: e.gameplay, loop: lv && lv.loop });
}
rows.sort((a, b) => a.score - b.score || a.id.localeCompare(b.id));
const dist = [1, 2, 3, 4, 5].map((s) => `${s}: ${rows.filter((r) => r.score === s).length}`).join(', ');
const out = ['# Music audit', '', 'Generated by `node tools/music_audit.js` (Overnight Oct 17, Part 12). Every track the game ships is rated 1-5 from measurements', '(loudness after the game\'s gain against the -20 LUFS loop / -17 LUFS sting target, dynamic range, the loop seam before and after', '`tools/loop_fix.js`, loop length) and from what the music list says it is for. **Nobody listened**: the scores rank what to audition first;', 'mood fit and melody need ears (see "What only listening can decide" at the end). The Drive folder Approved_Audio was not mounted', 'tonight, so the audit covers the in-game copies (the same files).', '', `Scores: ${dist}. Lowest first.`, '', '| Track | Name | Zone | Use | Score | Notes |', '|---|---|---|---|---|---|'];
for (const r of rows) out.push(`| ${r.id} | ${r.name} | ${r.zone} | ${r.use.replace(/\|/g, '/')} | ${r.score} | ${r.notes.join('; ')} |`);
out.push('', '## What only listening can decide', '', '- Mood fit per zone (does the Gainlands track feel macho-sunny, the D.N.A. deadpan-gloomy?) and whether battle tracks escalate.', '- Melodic repetitiveness inside long loops (a 160 s loop can still hammer one phrase).', '- Whether the loop-fixed seams (docs/audio/loop_fixes.md) sound natural: a 1.5 s crossfade blends a level jump but can smear a downbeat.');
fs.writeFileSync(path.join(root, 'docs/audio/music_audit.md'), out.join('\n') + '\n');
console.log(`music_audit: ${rows.length} tracks; ${dist}`);
console.log(rows.filter((r) => r.score <= 2).map((r) => `${r.id} (${r.score}): ${r.notes.join('; ')}`).join('\n'));
