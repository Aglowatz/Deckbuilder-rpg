// Rebalance Part H: writes docs/design/sheet_changes.md - every change the live Google Sheet needs, by tab, with exact values,
// by diffing the sheet snapshot CSVs (data/source/) against the pre-rebalance commit, plus the encounter rules, the enemy
// number changes and the new starting-deck rows.
//   node tools/sheet_changes.js [base-commit]      (default 90c5295c, the last commit before Part A)
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const repo = path.resolve(__dirname, '..');
const base = process.argv[2] || '90c5295c';

function parse(t){const rows=[];let row=[],f='',q=false;for(let i=0;i<t.length;i++){const c=t[i];if(q){if(c==='"'){if(t[i+1]==='"'){f+='"';i++;}else q=false;}else f+=c;}else{if(c==='"')q=true;else if(c===','){row.push(f);f='';}else if(c==='\n'){row.push(f);rows.push(row);row=[];f='';}else if(c==='\r'){}else f+=c;}}if(f.length||row.length){row.push(f);rows.push(row);}return rows;}
function old(file) { return execSync(`git show ${base}:${file}`, { cwd: repo, encoding: 'utf8', maxBuffer: 1 << 26 }); }
function now(file) { return fs.readFileSync(path.join(repo, file), 'utf8'); }
function cell(s) { return String(s).replace(/\|/g, '/').replace(/\r?\n\r?\n/g, ' // ').replace(/\r?\n/g, ' / '); }

const out = [];
out.push('# Sheet changes (Rebalance Parts A-H, Oct 18 2026)');
out.push('');
out.push(`Every change the live Google Sheet needs to match the game, by tab, with exact values. Generated by \`node tools/sheet_changes.js\` from the snapshot CSVs in \`data/source/\` diffed against commit \`${base}\` (the last one before the rebalance), plus \`data/encounters/modifiers.json\`, \`data/dungeons/dungeon_content.json\`, the zone enemy files and \`CampaignStart.STARTING_DECKS\`. The Design Guidance tab's rules rows are listed too in case the live tab differs from the snapshot. Why each change was made: \`docs/design/balance_log.md\`.`);
out.push('');

// ---- Card List ----------------------------------------------------------------------------------------------------------------
function cardsOf(text) { const map = {}; for (const r of parse(text).slice(1)) { const id = (r[14] || '').trim(); if (id) map[id] = { name: r[2], cost: r[3], type: r[4], text: r[5], pt: r[6], rarity: r[1] }; } return map; }
const before = cardsOf(old('data/source/card_list.csv'));
const after = cardsOf(now('data/source/card_list.csv'));
out.push('## Card List');
out.push('');
out.push('| Card ID | Name | Column | Old | New |');
out.push('|---|---|---|---|---|');
const columns = { cost: 'Casting Cost', pt: 'Power/Toughness', text: 'Card Text/Effect' };
let cardRows = 0;
const changedPerPath = {};
for (const id of Object.keys(after)) {
  if (!before[id]) { out.push(`| ${id} | ${cell(after[id].name)} | NEW ROW | - | cost ${cell(after[id].cost)}, ${cell(after[id].pt)}, "${cell(after[id].text)}" |`); cardRows++; continue; }
  let touched = false;
  for (const key of ['cost', 'pt', 'text']) {
    if ((before[id][key] || '').trim() !== (after[id][key] || '').trim()) {
      out.push(`| ${id} | ${cell(after[id].name)} | ${columns[key]} | ${cell(before[id][key])} | ${cell(after[id][key])} |`);
      cardRows++; touched = true;
    }
  }
  if (touched) { const p = id.split('-')[0]; changedPerPath[p] = (changedPerPath[p] || 0) + 1; }
}
out.push('');
out.push(`${cardRows} cell changes. Cards touched per prefix: ${Object.entries(changedPerPath).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
out.push('');

// ---- Token List ---------------------------------------------------------------------------------------------------------------
function tokensOf(text) { const map = {}; for (const r of parse(text).slice(1)) { const id = (r[0] || '').trim(); if (id) map[id] = { name: r[1], text: r[3], pt: r[4] }; } return map; }
const tb = tokensOf(old('data/source/token_list.csv')), ta = tokensOf(now('data/source/token_list.csv'));
out.push('## Token List');
out.push('');
out.push('| Token ID | Name | Column | Old | New |');
out.push('|---|---|---|---|---|');
let tokenRows = 0;
for (const id of Object.keys(ta)) {
  if (!tb[id]) { out.push(`| ${id} | ${cell(ta[id].name)} | NEW ROW | - | ${cell(ta[id].pt)} "${cell(ta[id].text)}" |`); tokenRows++; continue; }
  for (const key of ['text', 'pt']) if ((tb[id][key] || '').trim() !== (ta[id][key] || '').trim()) { out.push(`| ${id} | ${cell(ta[id].name)} | ${key === 'pt' ? 'Power/Toughness' : 'Card Text/Effect'} | ${cell(tb[id][key])} | ${cell(ta[id][key])} |`); tokenRows++; }
}
if (!tokenRows) out.push('| - | - | - | - | (no change) |');
out.push('');

// ---- Design Guidance ----------------------------------------------------------------------------------------------------------
function guidanceOf(text) { const map = {}; for (const r of parse(text).slice(1)) { const key = (r[1] || '').trim(); if (key) map[`${(r[0] || '').trim()}|${key}`] = { def: r[2], notes: r[3] }; } return map; }
const gb = guidanceOf(old('data/source/design_guidance.csv')), ga = guidanceOf(now('data/source/design_guidance.csv'));
out.push('## Design Guidance');
out.push('');
out.push('| Section | Term | Old definition | New definition |');
out.push('|---|---|---|---|');
let gRows = 0;
for (const key of Object.keys(ga)) { if (!gb[key] || (gb[key].def || '').trim() !== (ga[key].def || '').trim()) { const [section, term] = key.split('|'); out.push(`| ${section} | ${term} | ${cell(gb[key] ? gb[key].def : '-')} | ${cell(ga[key].def)} |`); gRows++; } }
if (!gRows) out.push('| - | - | - | (no change) |');
out.push('');

// ---- Dungeon List: encounter modifiers and enemy numbers ----------------------------------------------------------------------
out.push('## Dungeon List - encounter modifiers (new column "Encounter Modifiers", one line per rule)');
out.push('');
out.push('| Encounter (key) | Rule | Side | Effect (exact) | Shown as |');
out.push('|---|---|---|---|---|');
const mods = JSON.parse(now('data/encounters/modifiers.json'));
for (const [key, rules] of Object.entries(mods)) {
  if (key.startsWith('_')) continue;
  const seen = new Set();
  for (const r of rules) {
    const fields = Object.entries(r).filter(([k]) => !['name', 'text', 'icon', 'side', 'kind'].includes(k)).map(([k, v]) => `${k}=${JSON.stringify(v)}`).join(', ');
    out.push(`| ${cell(key)} | ${cell(r.name)} | ${r.side || 'enemy'} | ${r.kind}${fields ? ' (' + fields + ')' : ''} | "${cell(r.text)}" (icon ${r.icon || 'lorc/crossed-swords'}) |`);
  }
}
out.push('');

out.push('## Dungeon List - enemy numbers (dungeon_content.json foes and bosses that changed)');
out.push('');
out.push('| Dungeon | Node / foe | Old | New |');
out.push('|---|---|---|---|');
let dcb = {}, dca = {};
try { dcb = JSON.parse(old('data/dungeons/dungeon_content.json')).dungeons; } catch (e) { dcb = {}; }
dca = JSON.parse(now('data/dungeons/dungeon_content.json')).dungeons;
let dRows = 0;
for (const [dungeon, data] of Object.entries(dca)) {
  const prev = dcb[dungeon] || {};
  const foesA = data.foes || {}, foesB = prev.foes || {};
  for (const [node, spec] of Object.entries(foesA)) {
    const a = JSON.stringify(spec), b = JSON.stringify(foesB[node]);
    if (a !== b) { out.push(`| ${dungeon} | node ${node} | ${cell(b || '-')} | ${cell(a)} |`); dRows++; }
  }
  if (JSON.stringify(data.boss) !== JSON.stringify(prev.boss)) { out.push(`| ${dungeon} | boss | ${cell(JSON.stringify(prev.boss) || '-')} | ${cell(JSON.stringify(data.boss))} |`); dRows++; }
  if (JSON.stringify(data.defaults) !== JSON.stringify(prev.defaults)) { out.push(`| ${dungeon} | defaults | ${cell(JSON.stringify(prev.defaults) || '-')} | ${cell(JSON.stringify(data.defaults))} |`); dRows++; }
}
if (!dRows) out.push('| - | - | - | (no change) |');
out.push('');

out.push('## Zone roamers and gate fights (core/zone/*_enemies.gd: HP, deck size, AI)');
out.push('');
out.push('| File | Enemy | Old | New |');
out.push('|---|---|---|---|');
let zRows = 0;
for (const file of ['gainlands', 'dna', 'buffet', 'heap', 'capital']) {
  const rel = `core/zone/${file}_enemies.gd`;
  const parseEnemies = (text) => { const map = {}; const blocks = text.split(/\n\t\t(?=[A-Z_]+:\n)/); for (const b of blocks) { const m = b.match(/^([A-Z_]+):\n/); if (!m) continue; const hp = (b.match(/made\.hp = (\d+)/) || [])[1]; const recipe = (b.match(/made\.recipe = (.+)/) || [])[1]; const ai = (b.match(/made\.ai_name = "([^"]+)"/) || [])[1]; if (hp || recipe) map[m[1]] = `hp ${hp}, ${recipe}, ${ai}`; } return map; };
  let eb = {}; try { eb = parseEnemies(old(rel)); } catch (e) { eb = {}; }
  const ea = parseEnemies(now(rel));
  for (const [k, v] of Object.entries(ea)) if (eb[k] !== v) { out.push(`| ${rel} | ${k} | ${cell(eb[k] || '-')} | ${cell(v)} |`); zRows++; }
}
for (const rel of ['core/dungeon/trial_of_the_hollow.gd', 'core/dungeon/primm_boss.gd', 'core/dungeon/vault_guardian.gd', 'core/dungeon/ninja_boss.gd', 'core/dungeon/graveyard_boss.gd', 'core/dungeon/corrupted_npcs.gd', 'core/arena/arena_defs.gd']) {
  let b = ''; try { b = old(rel); } catch (e) { b = ''; }
  const a = now(rel);
  const grab = (t) => (t.match(/(STARTING_HP: int = \d+|hp = \d+|return \{[^\n]*\}|trimmed\("[^"]+", \d+, \d+\)|enemy_hp = \d+)/g) || []);
  const gb2 = grab(b), ga2 = grab(a);
  if (gb2.join('|') !== ga2.join('|')) { out.push(`| ${rel} | numbers | ${cell(gb2.filter(x => !ga2.includes(x)).join('; ') || '-')} | ${cell(ga2.filter(x => !gb2.includes(x)).join('; ') || '-')} |`); zRows++; }
}
if (!zRows) out.push('| - | - | - | (no change) |');
out.push('');

// ---- Starting decks -----------------------------------------------------------------------------------------------------------
out.push('## New rows: starting decks (one list per Path; 19 basic Infrastructure of the Path + these 26 cards)');
out.push('');
const cs = now('core/dungeon/campaign_start.gd');
const decksBlock = cs.slice(cs.indexOf('const STARTING_DECKS'), cs.indexOf('const GAME_PLANS'));
for (const pathName of ['BEEFCAKE', 'NECROCRAT', 'GOURMAND', 'REFUSEMANCER']) {
  const start = decksBlock.indexOf(`Affinity.Type.${pathName}: {`);
  const end = decksBlock.indexOf('}', start);
  const body = decksBlock.slice(start, end);
  const entries = [...body.matchAll(/"([A-Z]+-\d+)": (\d+)/g)].map(m => `${m[1]} x${m[2]} (${after[m[1]] ? cell(after[m[1]].name) : '?'})`);
  const total = [...body.matchAll(/"([A-Z]+-\d+)": (\d+)/g)].reduce((s, m) => s + Number(m[2]), 0);
  out.push(`- **${pathName.charAt(0) + pathName.slice(1).toLowerCase()}** (${total} cards + 19 ${({ BEEFCAKE: 'Powerhouse', NECROCRAT: 'Ghost Town', GOURMAND: 'Feastforge', REFUSEMANCER: 'Wasteworks' })[pathName]}): ${entries.join(', ')}`);
}
out.push('');
out.push('## Equipment and items');
out.push('');
out.push('See the "Part F" section of `docs/design/balance_log.md` for every equipment and consumable number that changed (the sheet has no equipment tab in the snapshot; add one if the live sheet tracks gear).');
out.push('');
// Overnight Oct 22: hand-written changes the snapshot diff cannot see (renamed characters, notes) live in sheet_changes_manual.md.
const manual = path.join(repo, 'docs/design/sheet_changes_manual.md');
if (fs.existsSync(manual)) {
	out.push(fs.readFileSync(manual, 'utf8').trim());
	out.push('');
}
fs.writeFileSync(path.join(repo, 'docs/design/sheet_changes.md'), out.join('\n') + '\n');
console.log(`wrote docs/design/sheet_changes.md: ${cardRows} card cells, ${tokenRows} token cells, ${gRows} guidance rows, ${dRows} dungeon rows, ${zRows} zone/boss rows`);
