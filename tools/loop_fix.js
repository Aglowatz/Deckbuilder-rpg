// Overnight Oct 17, Part 12: makes flagged music loops seamless.
//   node tools/loop_fix.js [--dry]
// For every looping track that data/source/audio_levels.csv flags (silent-gap, level-jump, level-step, or a click > 0.3), the
// in-game file assets/audio/music/<ID>.ogg is rebuilt: digital silence trimmed from both ends, then the seam baked as a crossfade
// (the last X seconds blended with the first X, the file starting X in), so the wrap continues the music instead of jumping, clicking
// or dropping out. X is 1.5 s for a level jump / step (blends the levels) and 0.08 s otherwise. The original is kept once in
// _art_source/audio_original/ (never exported) so `--restore` can put it back. Re-run after "import audio" (the importer copies the
// unfixed Drive files). Writes docs/audio/loop_fixes.md with before/after seam numbers.
const fs = require('fs'), path = require('path'), cp = require('child_process');
const root = path.join(__dirname, '..');
const ffdir = process.env.FFMPEG_DIR || 'C:/Users/asche/AppData/Local/Microsoft/WinGet/Packages/Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe/ffmpeg-9.0.2-full_build/bin';
const ffmpeg = path.join(ffdir, 'ffmpeg');
const dry = process.argv.includes('--dry');
const restore = process.argv.includes('--restore');
const musicDir = path.join(root, 'assets/audio/music');
const backupDir = path.join(root, '_art_source/audio_original');
fs.mkdirSync(backupDir, { recursive: true });

const rows = fs.readFileSync(path.join(root, 'data/source/audio_levels.csv'), 'utf8').trim().split('\n').slice(1).map((l) => l.split(','));
const targets = rows.filter((r) => r[2] === '1' && r[1].endsWith('.ogg') && ((r[13] || '').trim() !== '' || parseFloat(r[8]) > 0.3));

function pcm(file) {
	const raw = cp.spawnSync(ffmpeg, ['-v', 'error', '-i', file, '-f', 'f32le', '-ac', '2', '-ar', '48000', '-'], { maxBuffer: 1 << 30 }).stdout;
	return new Float32Array(raw.buffer, raw.byteOffset, Math.floor(raw.length / 4));
}
function seam(file) {
	const x = pcm(file); const n = Math.floor(x.length / 2); const sr = 48000;
	const rms = (a, b) => { let s = 0; for (let i = a; i < b; i++) s += x[2 * i] * x[2 * i] + x[2 * i + 1] * x[2 * i + 1]; return Math.sqrt(s / (2 * Math.max(1, b - a))); };
	const db = (v) => 20 * Math.log10(Math.max(v, 1e-9));
	let gap = 0; for (let i = n - 1; i > 0 && Math.abs(x[2 * i]) < 1e-4 && Math.abs(x[2 * i + 1]) < 1e-4; i--) gap++;
	for (let i = 0; i < n && Math.abs(x[2 * i]) < 1e-4 && Math.abs(x[2 * i + 1]) < 1e-4; i++) gap++;
	const step = Math.abs(x[0] - x[2 * (n - 1)]) + Math.abs(x[1] - x[2 * (n - 1) + 1]);
	return { gap: gap / sr, jump: db(rms(0, sr)) - db(rms(n - sr, n)), step: step, seconds: n / sr };
}

const report = ['# Loop fixes', '', 'Generated by `node tools/loop_fix.js` (Overnight Oct 17, Part 12). Each flagged loop had its silence trimmed and its seam baked as a crossfade; numbers are measured on the files the game plays. `jump` = loudness of the first second minus the last (dB); `gap` = digital silence at the wrap (s); `step` = the sample step at the wrap (0-4, lower is smoother).', '', '| Track | Flags | Crossfade | Before: gap / jump / step | After: gap / jump / step | Length |', '|---|---|---|---|---|---|'];
let done = 0;
for (const r of targets) {
	const id = r[0], flags = (r[13] || '').trim() || 'click';
	const file = path.join(musicDir, r[1]);
	const backup = path.join(backupDir, r[1]);
	if (!fs.existsSync(file)) continue;
	if (restore) { if (fs.existsSync(backup)) fs.copyFileSync(backup, file); continue; }
	if (!fs.existsSync(backup)) fs.copyFileSync(file, backup);
	const before = seam(backup);
	const x = /level-(jump|step)/.test(flags) ? 1.5 : 0.08;
	const trimmed = path.join(backupDir, id + '.trim.wav');
	cp.spawnSync(ffmpeg, ['-v', 'error', '-y', '-i', backup, '-af', 'silenceremove=start_periods=1:start_threshold=-60dB,areverse,silenceremove=start_periods=1:start_threshold=-60dB,areverse', trimmed]);
	const length = seam(trimmed).seconds;
	if (length < 3 * x + 4) { fs.unlinkSync(trimmed); continue; }
	const out = dry ? path.join(backupDir, id + '.fixed.ogg') : file;
	const filter = `[0:a]atrim=start=${x},asetpts=PTS-STARTPTS[body];[0:a]atrim=end=${x},asetpts=PTS-STARTPTS[head];[body][head]acrossfade=d=${x}:c1=qsin:c2=qsin[out]`;
	const run = cp.spawnSync(ffmpeg, ['-v', 'error', '-y', '-i', trimmed, '-filter_complex', filter, '-map', '[out]', '-c:a', 'libvorbis', '-q:a', '5', out], { encoding: 'utf8' });
	fs.unlinkSync(trimmed);
	if (run.status !== 0) { console.log('loop_fix: FAILED', id, run.stderr); continue; }
	const after = seam(out);
	report.push(`| ${id} | ${flags} | ${x} s | ${before.gap.toFixed(2)} / ${before.jump.toFixed(1)} / ${before.step.toFixed(3)} | ${after.gap.toFixed(2)} / ${after.jump.toFixed(1)} / ${after.step.toFixed(3)} | ${before.seconds.toFixed(1)} -> ${after.seconds.toFixed(1)} s |`);
	done++;
}
if (!restore) fs.writeFileSync(path.join(root, 'docs/audio/loop_fixes.md'), report.join('\n') + '\n');
console.log(`loop_fix: ${restore ? 'restored' : 'fixed'} ${restore ? targets.length : done} of ${targets.length} flagged loops${dry ? ' (dry run)' : ''}`);
