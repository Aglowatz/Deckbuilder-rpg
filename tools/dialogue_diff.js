// Overnight Oct 16, Block 4d: writes docs/design/dialogue_rewrite.md - every story line the dialogue rewrite changed, old beside new, so any
// line can be compared and reverted in the morning. Compares each story file (and the other text sources below) against the commit named
// on the command line (default: the tag pre-overnight-oct16).
//   node tools/dialogue_diff.js [base-ref] [output .md, default docs/design/dialogue_rewrite.md]
// Oct 21: also NPC barks (npcs.json) and the Old Well text; loading tips are compared line by line.
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const base = process.argv[2] || 'pre-overnight-oct16';
const output = process.argv[3] || 'docs/design/dialogue_rewrite.md';
const FILES = [
	'data/story/intro_story.tres', 'data/story/gainlands_story.tres', 'data/story/dna_story.tres', 'data/story/gourmand_story.tres',
	'data/story/refusemancer_story.tres', 'data/story/capital_story.tres', 'data/dungeons/dungeon_content.json', 'data/loading/loading_tips.txt',
	'data/npcs/npcs.json', 'data/story/old_well_story.json',
	'core/quests/quest_definitions.gd', 'core/quests/zone_quest_definitions.gd', 'core/data/expansion_gear.gd',
];

// "key": ["line", "line"] entries of a story .tres (one per line), or `name = Array[String](["..."])` exports.
function entries(text) {
	const result = new Map();
	for (const raw of text.split('\n')) {
		let m = raw.match(/^"([^"]+)":\s*(\[.*\]),?\s*$/);
		if (!m) m = raw.match(/^([a-z_]+_lines)\s*=\s*Array\[String\]\((\[.*\])\)\s*$/);
		if (!m) continue;
		try { result.set(m[1], JSON.parse(m[2])); } catch (e) { result.set(m[1], [m[2]]); }
	}
	return result;
}

// Quoted strings of a script or JSON file (titles, summaries, objective texts...), keyed by their line number in the base version.
function strings(text) {
	const result = [];
	const re = /"((?:[^"\\]|\\.){12,})"/g;
	let m;
	while ((m = re.exec(text)) !== null) result.push(m[1]);
	return result;
}

function esc(s) { return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '); }

// Loading tips: one tip per line ("kind | text"), with the line number in the new file.
function tipLines(text) {
	return text.split('\n').map((l, i) => [i + 1, l.trim()]).filter(([, l]) => l && !l.startsWith('#'));
}

let out = `# Dialogue rewrite: old and new lines\n\nGenerated by \`node tools/dialogue_diff.js ${base}${process.argv[3] ? ' ' + output : ''}\` against \`${base}\` (the commit before the pass).\n` +
	`Every changed line of the story files is listed with its key; to revert one, copy the old text back into the file named in its section.\n` +
	`Voice rules: docs/design/voice_bible.md.\n\n`;
let changed = 0;
for (const file of FILES) {
	let before = '';
	try { before = execSync(`git show ${base}:${file}`, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 26, stdio: ['ignore', 'pipe', 'ignore'] }); } catch (e) { before = ''; }
	const after = fs.existsSync(path.join(root, file)) ? fs.readFileSync(path.join(root, file), 'utf8') : '';
	const rows = [];
	if (file.endsWith('.tres')) {
		const a = entries(before), b = entries(after);
		for (const [key, lines] of b) {
			const old = a.get(key);
			if (old === undefined) { rows.push([key, '(new)', lines.join(' / ')]); continue; }
			if (JSON.stringify(old) !== JSON.stringify(lines)) rows.push([key, old.join(' / '), lines.join(' / ')]);
		}
	} else if (file.endsWith('.txt')) {
		const a = tipLines(before), b = tipLines(after);
		const oldSet = new Set(a.map(([, l]) => l)), newSet = new Set(b.map(([, l]) => l));
		const gone = a.filter(([, l]) => !newSet.has(l)), added = b.filter(([, l]) => !oldSet.has(l));
		const n = Math.max(gone.length, added.length);
		for (let i = 0; i < n; i++) rows.push([added[i] ? `line ${added[i][0]}` : `#${i + 1}`, gone[i] ? gone[i][1] : '', added[i] ? added[i][1] : '']);
	} else {
		const a = new Set(strings(before)), b = strings(after);
		const gone = strings(before).filter((s) => !after.includes(s));
		const added = b.filter((s) => !a.has(s));
		const n = Math.max(gone.length, added.length);
		for (let i = 0; i < n; i++) rows.push([`#${i + 1}`, gone[i] || '', added[i] || '']);
	}
	if (rows.length === 0) continue;
	changed += rows.length;
	out += `## ${file} (${rows.length})\n\n| Key | Old | New |\n|---|---|---|\n`;
	for (const r of rows) out += `| ${esc(r[0])} | ${esc(r[1])} | ${esc(r[2])} |\n`;
	out += '\n';
}
fs.writeFileSync(path.join(root, output), out);
console.log(`dialogue_diff: ${changed} changed lines written to ${output}`);
