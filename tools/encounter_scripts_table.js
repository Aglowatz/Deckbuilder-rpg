// Overnight Oct 23: prints a markdown table of every scripted boss/elite trigger (data/encounters/encounter_scripts.json).
//   node tools/encounter_scripts_table.js > docs/design/encounter_scripts.md
const fs = require('fs');
const data = JSON.parse(fs.readFileSync('data/encounters/encounter_scripts.json', 'utf8'));
const when = (w) => {
  switch (w.type) {
    case 'hp_below': return `HP <= ${w.pct}%`;
    case 'turn': return `its turn ${w.turn} (warned the turn before)`;
    case 'units_died': return `${w.count} ${w.side === 'foe' ? 'of your' : w.side === 'any' ? '' : 'of its'} units died`.replace('  ', ' ');
    case 'foe_units_at_least': return `you have ${w.count} units`;
    case 'own_units_at_most': return `it has <= ${w.count} units`;
    case 'foe_hp_below': return `your HP <= ${w.pct}%`;
  }
  return w.type;
};
const lines = [
  '# Scripted boss and elite events (Overnight Oct 23, Part 1)',
  '',
  'Generated by `node tools/encounter_scripts_table.js` from `data/encounters/encounter_scripts.json` (engine: `core/dungeon/encounter_scripts.gd`).',
  'Every trigger fires once per fight, is listed with the rule icons from the start (amber), and a timed one is announced the turn before.',
  '',
  '| Encounter | Trigger | When | What happens | Line |',
  '|---|---|---|---|---|',
];
for (const [key, list] of Object.entries(data)) {
  if (key.startsWith('_')) continue;
  for (const t of list) {
    lines.push(`| ${key} | ${t.name} | ${when(t.when)} | ${t.text.replace(/\|/g, '/')} | ${t.line.replace(/\|/g, '/')} |`);
  }
}
console.log(lines.join('\n'));
