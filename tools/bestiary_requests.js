// Overnight Oct 17 (Phase 2 cycle 15): ChatGPT-ready picture requests for every Bestiary entry.
//   node tools/bestiary_requests.js
// Reads data/bestiary/bestiary.json and the portrait style lock from data/source/npc_list.csv; writes docs/art/bestiary_image_requests.md.
// Save each picture as assets/art/bestiary/<ID>.png (square); the Collection Book and the battle plate use it as soon as it exists (Bestiary.art).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/bestiary/bestiary.json'), 'utf8'));
const entries = data.entries || data;
const csv = fs.readFileSync(path.join(root, 'data/source/npc_list.csv'), 'utf8');
const lockLine = csv.split('\n').find((line) => line.startsWith('PORTRAIT STYLE LOCK')) || '';
const lock = lockLine.replace(/^PORTRAIT STYLE LOCK,"?/, '').replace(/^Paste before every Portrait Art Direction: /, '').replace(/"?,*\r?$/, '').replace(/""/g, '"').replace(/^"|"$/g, '');
// Same rule as Bestiary.art_id (GDScript): upper case, letters and digits, everything else a single dash.
const artId = (name) => 'BST-' + name.toUpperCase().replace(/[^A-Z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const lines = ['# Bestiary image requests', '',
	`Generated by \`node tools/bestiary_requests.js\` (Overnight Oct 17, Phase 2 cycle 15). ${entries.length} enemies and bosses have no picture yet: the Collection Book and the battle plate show a generic icon. Save each one as a **square PNG** named with its ID (e.g. \`BST-CAVE-SCAVENGER.png\`) and approve it into the Drive folder \`Card Game Art/Approved_Bestiary\`; \`bash tools/import_bestiary.sh\` ("import bestiary") copies it to \`assets/art/bestiary/<ID>.webp\` and the game picks it up - in the Bestiary (a dark silhouette until met) and as the enemy's round portrait in battle. Batches of 20, ready to paste.`, '',
	'**Style lock** (paste first for every picture):', '', '> ' + lock + ' Square 1:1 image, the character centred, head and upper body filling most of the frame (it is shown inside a circle), a soft dark painted background, no text, no frame.', ''];
for (let b = 0; b < entries.length; b += 20) {
	lines.push(`## Batch ${b / 20 + 1}`, '');
	for (const e of entries.slice(b, b + 20)) {
		const role = e.kind === 'boss' ? 'a boss' : (e.kind === 'roamer' ? 'an enemy that roams the overworld' : 'a dungeon foe');
		lines.push(`- **${artId(e.name)}** - ${e.name} (${role}, ${e.where}): ${e.blurb}`);
	}
	lines.push('');
}
fs.writeFileSync(path.join(root, 'docs/art/bestiary_image_requests.md'), lines.join('\n'));
console.log(`bestiary_requests: ${entries.length} requests`);
